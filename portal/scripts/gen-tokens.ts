import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

const root = join(import.meta.dirname, "../..")
type Tokens = {
  color: Record<string, { light: string; dark: string }>
  radius: Record<string, string>
  space: Record<string, string>
  font: Record<string, string>
}
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8")) as Tokens

const write = (path: string, content: string) => {
  mkdirSync(dirname(path), { recursive: true })
  if (existsSync(path) && readFileSync(path, "utf8") === content) return
  writeFileSync(path, content)
  console.log(`written  ${path.slice(root.length + 1)}`)
}

const colors = Object.entries(tokens.color)
const vars = (mode: "light" | "dark", indent: string) => colors.map(([k, v]) => `${indent}--${k}: ${v[mode]};`).join("\n")
const css = `/* Code generated by make generate. DO NOT EDIT. */
:root {
${vars("light", "  ")}
}

.dark {
${vars("dark", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${vars("dark", "    ")}
  }
}

@theme inline {
${colors.map(([k]) => `  --color-${k}: var(--${k});`).join("\n")}
${Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v};`).join("\n")}
${Object.entries(tokens.font).map(([k, v]) => `  --font-${k}: ${v};`).join("\n")}
}
`
if (existsSync(join(root, "web/packages/ui"))) write(join(root, "web/packages/ui/src/tokens.gen.css"), css)

function rgba(value: string): [number, number, number, number] {
  const hex = value.match(/^#([0-9a-f]{6})$/i)
  if (hex) {
    const n = parseInt(hex[1], 16)
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1]
  }
  const fn = value.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)$/)
  if (fn) return [Number(fn[1]), Number(fn[2]), Number(fn[3]), fn[4] === undefined ? 1 : Number(fn[4])]
  throw new Error(`Unreadable color: ${value}`)
}
const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
const ident = (s: string) => (/^\d/.test(s) ? `s${s}` : camel(s))
const rem = (v: string) => {
  const m = v.match(/^([\d.]+)rem$/)
  if (!m) throw new Error(`Only rem values allowed: ${v}`)
  return Number(m[1]) * 16
}
const swiftColor = (v: string) => {
  const [r, g, b, a] = rgba(v)
  return `RGBA(${r}, ${g}, ${b}, ${a})`
}
const swift = `// Code generated by make generate. DO NOT EDIT.

import CoreGraphics

public enum Tokens {
    public enum Colors {
${colors.map(([k, v]) => `        public static let ${camel(k)} = DynamicColor(light: ${swiftColor(v.light)}, dark: ${swiftColor(v.dark)})`).join("\n")}
    }

    public enum Radius {
${Object.entries(tokens.radius).map(([k, v]) => `        public static let ${ident(k)}: CGFloat = ${rem(v)}`).join("\n")}
    }

    public enum Space {
${Object.entries(tokens.space).map(([k, v]) => `        public static let ${ident(k)}: CGFloat = ${rem(v)}`).join("\n")}
    }
}
`
const kit = existsSync(join(root, "ios")) ? readdirSync(join(root, "ios")).find((d) => d.endsWith("Kit")) : undefined
const design = kit ? readdirSync(join(root, "ios", kit, "Sources")).find((d) => d.endsWith("Design")) : undefined
if (kit && design) write(join(root, "ios", kit, "Sources", design, "Tokens.gen.swift"), swift)
